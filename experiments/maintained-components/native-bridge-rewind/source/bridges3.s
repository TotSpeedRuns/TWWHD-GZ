.balign 4
.global _gz_brg_plan_length
.type _gz_brg_plan_length,@function
_gz_brg_plan_length:
    stwu 1,-128(1)
    stw 0,40(1)
    stw 3,44(1)
    stw 4,48(1)
    stw 5,52(1)
    stw 6,56(1)
    stw 7,60(1)
    stw 8,64(1)
    stw 9,68(1)
    stw 10,72(1)
    stw 11,76(1)
    stw 12,80(1)
    mflr 0
    stw 0,84(1)
    mfcr 0
    stw 0,88(1)
    mfctr 0
    stw 0,92(1)
    mfxer 0
    stw 0,96(1)
    mr 3,9
    bl _gz_brg_component_bytes
    stw 3,100(1)
    lwz 0,96(1)
    mtxer 0
    lwz 0,92(1)
    mtctr 0
    lwz 0,88(1)
    mtcr 0
    lwz 0,84(1)
    mtlr 0
    lwz 3,44(1)
    lwz 4,48(1)
